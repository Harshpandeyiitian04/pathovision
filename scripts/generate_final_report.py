#!/usr/bin/env python3
"""Create a human-readable final results summary from measured JSON/CSV artifacts."""
from __future__ import annotations

import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import argparse
from pathlib import Path
import json
import pandas as pd


def dataframe_to_markdown(df: pd.DataFrame) -> str:
    if df.empty:
        return "_No rows available._"
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "| " + " | ".join(["---"] * len(cols)) + " |"]
    for _, row in df.iterrows():
        vals = [str(row[c]).replace("|", "\\|") for c in df.columns]
        lines.append("| " + " | ".join(vals) + " |")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/default.yaml")
    args = parser.parse_args()
    results = Path("results")
    metrics_path = results / "metrics" / "test_metrics.json"
    report_path = results / "metrics" / "final_report.json"
    if not metrics_path.exists() or not report_path.exists():
        raise FileNotFoundError("Run scripts/evaluate.py before generating FINAL_RESULTS.md")
    metrics = json.loads(metrics_path.read_text())
    report = json.loads(report_path.read_text())
    lines = ["# PathoVision Final Results", "", "These values were generated by the executed PathoVision pipeline.", "", "## Test Metrics", ""]
    for key in ("accuracy", "precision", "recall", "f1", "roc_auc", "specificity", "sensitivity", "support"):
        value = metrics.get(key)
        lines.append(f"- **{key}**: {value}")
    lines += ["", "## Aggregation Comparison", ""]
    agg_path = results / "metrics" / "aggregation_comparison.csv"
    if agg_path.exists():
        lines.append(dataframe_to_markdown(pd.read_csv(agg_path)))
    lines += ["", "## Magnification Analysis", ""]
    mag_path = results / "metrics" / "by_magnification.csv"
    if mag_path.exists():
        lines.append(dataframe_to_markdown(pd.read_csv(mag_path)))
    (results / "FINAL_RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(results / "FINAL_RESULTS.md")

if __name__ == "__main__":
    main()
